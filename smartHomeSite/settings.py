def env_bool(name, default=False):
    """Wartość logiczna ze zmiennej środowiskowej: 1/0, true/false, yes/no, on/off."""
    value = os.environ.get(name, '').strip().lower()
    if not value:
        return default
    if value in ('1', 'true', 'yes', 'on'):
        return True
    if value in ('0', 'false', 'no', 'off'):
        return False
    raise ImproperlyConfigured(f'{name}: invalid boolean value {value!r}')


def env_list(name):
    """Lista ze zmiennej środowiskowej rozdzielonej przecinkami (puste elementy pomijane)."""
    return [item.strip() for item in os.environ.get(name, '').split(',') if item.strip()]


